//! Generates `amalfi_tokens.rs` from `data/amalfi-tokens.json` and `data/amalfi-motion.md`
//! (copies of silica-desktop's `docs/design/amalfi/tokens.json` and `motion.md`; the port of
//! silica_ui's `tool/gen_amalfi_tokens.dart`), and `silica_symbols.rs` from
//! `data/silica-symbols-codepoints.json` (silica-icons `fonts/codepoints.json`).

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

type Result<T> = std::result::Result<T, String>;

pub fn generate(out: &Path) -> Result<()> {
    let tokens = read_json("data/amalfi-tokens.json")?;
    let motion = std::fs::read_to_string("data/amalfi-motion.md").map_err(|e| e.to_string())?;
    let mut code = String::new();
    header(&mut code, &tokens);
    colors(&mut code, &tokens)?;
    typography(&mut code, &tokens)?;
    numbers(&mut code, &tokens)?;
    shadows(&mut code, &tokens)?;
    states(&mut code, &tokens)?;
    window_controls(&mut code, &tokens)?;
    materials(&mut code, &tokens)?;
    motion_tokens(&mut code, &motion)?;
    std::fs::write(out.join("amalfi_tokens.rs"), code).map_err(|e| e.to_string())?;

    let points = read_json("data/silica-symbols-codepoints.json")?;
    std::fs::write(out.join("silica_symbols.rs"), symbols(&points)?).map_err(|e| e.to_string())
}

fn read_json(path: &str) -> Result<Value> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
    serde_json::from_str(&text).map_err(|e| format!("{path}: {e}"))
}

fn header(code: &mut String, t: &Value) {
    let _ = writeln!(
        code,
        "// GENERATED by libvetro's build script from data/amalfi-tokens.json and\n\
         // data/amalfi-motion.md. Do not edit.\n//\n// {}: {}\n",
        t["name"].as_str().unwrap_or_default(),
        t["source"].as_str().unwrap_or_default()
    );
}

/// `Accent/Amalfi Pressed` → `accent_amalfi_pressed`.
fn snake(name: &str) -> String {
    let mut s = String::new();
    let mut last_us = true;
    let mut prev_lower = false;
    for c in name.chars() {
        if c.is_ascii_uppercase() && prev_lower && !last_us {
            s.push('_');
        }
        prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        if c.is_ascii_alphanumeric() {
            s.push(c.to_ascii_lowercase());
            last_us = false;
        } else if !last_us {
            s.push('_');
            last_us = true;
        }
    }
    while s.ends_with('_') {
        s.pop();
    }
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, '_');
    }
    s
}

fn upper(name: &str) -> String {
    snake(name).to_ascii_uppercase()
}

fn color_lit(text: &str) -> Result<String> {
    let hex = text
        .trim()
        .strip_prefix('#')
        .ok_or_else(|| format!("bad colour {text}"))?;
    let v = u32::from_str_radix(hex, 16).map_err(|_| format!("bad colour {text}"))?;
    let v = match hex.len() {
        6 => (v << 8) | 0xff,
        8 => v,
        _ => return Err(format!("bad colour {text}")),
    };
    Ok(format!("Color::from_u32(0x{v:08x})"))
}

fn num(v: &Value) -> Result<f32> {
    v.as_f64()
        .map(|f| f as f32)
        .ok_or_else(|| format!("not a number: {v}"))
}

fn f(v: f32) -> String {
    let s = format!("{v:?}");
    if s.contains('.') || s.contains('e') {
        s
    } else {
        format!("{s}.0")
    }
}

fn colors(code: &mut String, t: &Value) -> Result<()> {
    let light = t["colors"]["light"]
        .as_object()
        .ok_or("colors.light missing")?;
    let dark = t["colors"]["dark"].as_object().ok_or("colors.dark missing")?;
    // The system palette: the names both appearances have (the apps' own are looked up).
    let common: Vec<&String> = light
        .keys()
        .filter(|k| dark.contains_key(*k) && !k.starts_with("App/"))
        .collect();
    code.push_str(
        "/// The system colours of one appearance (`colors` in tokens.json; the apps' own \
         palettes are looked up with [`app_color`]).\n\
         #[derive(Debug, Clone, Copy, PartialEq)]\npub struct Palette {\n",
    );
    for k in &common {
        let _ = writeln!(code, "    /// `{k}`.\n    pub {}: Color,", snake(k));
    }
    code.push_str("}\n\n");
    for (name, map) in [("LIGHT", light), ("DARK", dark)] {
        let _ = writeln!(
            code,
            "/// The {} palette.\npub const {name}: Palette = Palette {{",
            name.to_ascii_lowercase()
        );
        for k in &common {
            let v = map[k.as_str()].as_str().ok_or("colour not a string")?;
            let _ = writeln!(code, "    {}: {},", snake(k), color_lit(v)?);
        }
        code.push_str("};\n\n");
    }
    for (name, map) in [("LIGHT_ALL", light), ("DARK_ALL", dark)] {
        let mut keys: Vec<&String> = map.keys().collect();
        keys.sort();
        let _ = writeln!(
            code,
            "/// Every colour of the appearance by token name, sorted.\n\
             pub static {name}: &[(&str, Color)] = &["
        );
        for k in keys {
            let v = map[k.as_str()].as_str().ok_or("colour not a string")?;
            let _ = writeln!(code, "    ({k:?}, {}),", color_lit(v)?);
        }
        code.push_str("];\n\n");
    }
    Ok(())
}

fn typography(code: &mut String, t: &Value) -> Result<()> {
    let ty = t["typography"].as_object().ok_or("typography missing")?;
    code.push_str("/// The type styles (`typography`).\npub mod typography {\n    use super::TypeStyle;\n\n");
    let mut all = Vec::new();
    for (name, v) in ty {
        let size = num(&v["size"])?;
        let line = v["lineHeight"].as_f64().map(|x| x as f32);
        let weight = v["weight"].as_u64().unwrap_or(400);
        let tracking = v["tracking"].as_f64().unwrap_or(0.0) as f32;
        let family = v["family"].as_str().unwrap_or("Inter");
        let features: Vec<String> = v["features"]
            .as_array()
            .map(|a| {
                a.iter()
                    .filter_map(|x| x.as_str().map(|s| format!("{s:?}")))
                    .collect()
            })
            .unwrap_or_default();
        let id = upper(name);
        let _ = writeln!(
            code,
            "    /// `{name}`: {family} {size} / {} weight {weight}.\n    pub const {id}: TypeStyle = TypeStyle {{ name: {name:?}, family: {family:?}, size: {}, line_height: {}, weight: {weight}, tracking: {}, features: &[{}] }};\n",
            line.map(|l| l.to_string()).unwrap_or_else(|| "natural".into()),
            f(size),
            line.map(|l| format!("Some({})", f(l))).unwrap_or_else(|| "None".into()),
            f(tracking),
            features.join(", ")
        );
        all.push(id);
    }
    let _ = writeln!(
        code,
        "    /// Every style.\n    pub static ALL: &[TypeStyle] = &[{}];\n}}\n",
        all.join(", ")
    );
    Ok(())
}

fn numbers(code: &mut String, t: &Value) -> Result<()> {
    let groups = [
        ("spacing", "Spacing (`spacing`)."),
        ("controlHeights", "Control heights (`controlHeights`)."),
        ("controlIcons", "Icon sizes in controls (`controlIcons`)."),
        ("radii", "Corner radii (`radii`)."),
        ("grid", "The layout grid (`grid`)."),
        ("focus", "The focus halo (`focus`)."),
        ("switch", "The switch (`switch`)."),
    ];
    for (key, doc) in groups {
        let obj = t[key].as_object().ok_or_else(|| format!("{key} missing"))?;
        let _ = writeln!(code, "/// {doc}\npub mod {} {{", snake(key));
        write_numbers(code, obj, "    ");
        code.push_str("}\n\n");
    }
    Ok(())
}

fn write_numbers(code: &mut String, obj: &serde_json::Map<String, Value>, indent: &str) {
    for (k, v) in obj {
        if let Some(n) = v.as_f64() {
            let _ = writeln!(
                code,
                "{indent}/// `{k}`.\n{indent}pub const {}: f32 = {};",
                upper(k),
                f(n as f32)
            );
        } else if let Some(o) = v.as_object() {
            if o.values().any(|x| x.is_number()) {
                let _ = writeln!(code, "{indent}/// `{k}`.\n{indent}pub mod {} {{", snake(k));
                write_numbers(code, o, &format!("{indent}    "));
                let _ = writeln!(code, "{indent}}}");
            }
        }
    }
}

fn shadow_lit(v: &Value) -> Result<String> {
    Ok(format!(
        "Shadow {{ color: {}, x: {}, y: {}, blur: {}, spread: 0.0 }}",
        color_lit(v["color"].as_str().ok_or("shadow colour")?)?,
        f(v["x"].as_f64().unwrap_or(0.0) as f32),
        f(v["y"].as_f64().unwrap_or(0.0) as f32),
        f(v["blur"].as_f64().unwrap_or(0.0) as f32)
    ))
}

fn shadows(code: &mut String, t: &Value) -> Result<()> {
    let s = &t["shadows"];
    code.push_str("/// The shadow levels (`shadows`): 1 small raised controls, 2 Glass/Regular objects, 3 windows and Glass/Thick.\npub mod shadows {\n    use super::{Color, Shadow};\n\n");
    for app in ["light", "dark"] {
        let _ = writeln!(
            code,
            "    /// Levels 1–3, {app}.\n    pub const {}: [Shadow; 3] = [{}, {}, {}];",
            app.to_ascii_uppercase(),
            shadow_lit(&s[app]["1"])?,
            shadow_lit(&s[app]["2"])?,
            shadow_lit(&s[app]["3"])?
        );
    }
    let _ = writeln!(
        code,
        "    /// Text and status items drawn straight on the wallpaper (light only).\n    pub const ON_PHOTO: Shadow = {};\n}}\n",
        shadow_lit(&s["onPhoto"])?
    );
    Ok(())
}

fn states(code: &mut String, t: &Value) -> Result<()> {
    let s = &t["states"];
    let disabled = s["disabled"].as_str().unwrap_or_default();
    let pct: f32 = disabled
        .split_whitespace()
        .find_map(|w| w.parse::<f32>().ok())
        .unwrap_or(35.0);
    let _ = writeln!(
        code,
        "/// Interaction states (`states`).\npub mod states {{\n    use super::Color;\n\n    /// Hover wash, light.\n    pub const HOVER_LIGHT: Color = {};\n    /// Hover wash, dark.\n    pub const HOVER_DARK: Color = {};\n    /// Press wash, light.\n    pub const PRESS_LIGHT: Color = {};\n    /// Press wash, dark.\n    pub const PRESS_DARK: Color = {};\n    /// Opacity of a disabled control ({disabled}).\n    pub const DISABLED_OPACITY: f32 = {};\n}}\n",
        color_lit(s["hoverOverlay"]["light"].as_str().ok_or("hover")?)?,
        color_lit(s["hoverOverlay"]["dark"].as_str().ok_or("hover")?)?,
        color_lit(s["pressOverlay"]["light"].as_str().ok_or("press")?)?,
        color_lit(s["pressOverlay"]["dark"].as_str().ok_or("press")?)?,
        f(pct / 100.0)
    );
    Ok(())
}

fn window_controls(code: &mut String, t: &Value) -> Result<()> {
    let w = &t["windowControls"];
    code.push_str("/// The window buttons (`windowControls`, measured values).\npub mod window_controls {\n    use super::Color;\n\n");
    for k in ["dot", "firstCentreX", "pitch"] {
        let _ = writeln!(
            code,
            "    /// `{k}`.\n    pub const {}: f32 = {};",
            upper(k),
            f(num(&w[k])?)
        );
    }
    for b in ["close", "minimise", "zoom"] {
        let fill = w[b]["fill"].as_array().ok_or("fill")?;
        let rim = w[b]["rim"].as_str().ok_or("rim")?;
        let mut parts = rim.split_whitespace();
        let rim_c = parts.next().ok_or("rim colour")?;
        let rim_w: f32 = parts.next().and_then(|x| x.parse().ok()).unwrap_or(0.5);
        let _ = writeln!(
            code,
            "    /// `{b}`: fill gradient top, bottom; rim colour and width.\n    pub const {}: ([Color; 2], Color, f32) = ([{}, {}], {}, {});",
            upper(b),
            color_lit(fill.first().and_then(Value::as_str).ok_or("fill 0")?)?,
            color_lit(fill.get(1).and_then(Value::as_str).ok_or("fill 1")?)?,
            color_lit(rim_c)?,
            f(rim_w)
        );
    }
    code.push_str("}\n\n");
    Ok(())
}

fn opt_color(v: &Value) -> Result<String> {
    match v.as_str() {
        Some(s) => Ok(format!("Some({})", color_lit(s)?)),
        None => Ok("None".into()),
    }
}

fn materials(code: &mut String, t: &Value) -> Result<()> {
    let m = t["materials"].as_object().ok_or("materials missing")?;
    code.push_str("/// The materials (`materials`): glass, blurs and scrims, per appearance.\npub mod materials {\n    use super::{Color, MaterialToken};\n\n");
    let mut names = Vec::new();
    for (name, v) in m {
        if name.starts_with("Scrim/") {
            let stops = v["stops"].as_array().ok_or("scrim stops")?;
            let mut lits = Vec::new();
            for s in stops {
                let pos = s.get(0).map(num).transpose()?.unwrap_or(0.0);
                let c = s.get(1).and_then(Value::as_str).ok_or("scrim colour")?;
                lits.push(format!("({}, {})", f(pos), color_lit(c)?));
            }
            let _ = writeln!(
                code,
                "    /// `{name}`: a top-to-bottom gradient.\n    pub const {}: &[(f32, Color)] = &[{}];\n",
                upper(name),
                lits.join(", ")
            );
            continue;
        }
        for app in ["light", "dark"] {
            let blur = v["backgroundBlur"]
                .as_f64()
                .or_else(|| v["blur"].as_f64())
                .unwrap_or(0.0) as f32;
            let saturation = v["saturation"].as_f64().unwrap_or(1.0) as f32;
            let brightness = match &v["brightness"] {
                Value::Number(n) => n.as_f64().unwrap_or(1.0) as f32,
                Value::Object(o) => o.get(app).and_then(Value::as_f64).unwrap_or(1.0) as f32,
                _ => 1.0,
            };
            let tint = match &v["tint"] {
                Value::Object(o) => opt_color(o.get(app).unwrap_or(&Value::Null))?,
                _ => opt_color(&v["fill"])?,
            };
            let rim_inside = match &v["rimInside"] {
                Value::Object(o) => opt_color(o.get(app).unwrap_or(&Value::Null))?,
                _ => "None".into(),
            };
            let rim_light = match &v["rimLight"] {
                Value::Object(o) => opt_color(o.get(app).unwrap_or(&Value::Null))?,
                _ => "None".into(),
            };
            let r = &v["refraction"];
            let shadow_level = v["shadow"]
                .as_str()
                .and_then(|s| s.strip_prefix("shadows."))
                .and_then(|s| s.parse::<u8>().ok())
                .unwrap_or(0);
            let _ = writeln!(
                code,
                "    /// `{name}`, {app}.\n    pub const {}_{}: MaterialToken = MaterialToken {{ name: {name:?}, blur: {}, saturation: {}, brightness: {}, tint: {tint}, rim_inside: {rim_inside}, rim_light: {rim_light}, distortion: {}, depth: {}, chromatic_aberration: {}, magnification: {}, specular: {}, shadow_level: {shadow_level}, lens: {} }};\n",
                upper(name),
                app.to_ascii_uppercase(),
                f(blur),
                f(saturation),
                f(brightness),
                f(r["distortion"].as_f64().unwrap_or(0.0) as f32),
                f(r["depth"].as_f64().unwrap_or(0.0) as f32),
                f(r["chromaticAberration"].as_f64().unwrap_or(0.0) as f32),
                f(r["magnification"].as_f64().unwrap_or(1.0) as f32),
                v["specularHighlights"].as_bool().unwrap_or(false),
                v["lens"].as_bool().unwrap_or(false),
            );
        }
        names.push(upper(name));
    }
    let _ = writeln!(
        code,
        "    /// Every material: (light, dark).\n    pub static ALL: &[(MaterialToken, MaterialToken)] = &[{}];\n}}\n",
        names
            .iter()
            .map(|n| format!("({n}_LIGHT, {n}_DARK)"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    Ok(())
}

/// Parses the motion tables: `| \`spring.x\` | response | ζ | k | c | … |` and
/// `| \`fade.x\` | 100 ms | ease-out (0.2, 0, 0, 1) | … |`.
fn motion_tokens(code: &mut String, md: &str) -> Result<()> {
    code.push_str("/// Motion tokens for animations never measured (`motion.md`): measured curves live with their components.\npub mod motion {\n    use super::{Cubic, SpringToken};\n\n");
    let mut curves: Vec<(String, [f32; 4])> = Vec::new();
    let mut seen = BTreeSet::new();
    for line in md.lines() {
        let cells: Vec<&str> = line.split('|').map(str::trim).collect();
        let Some(name) = cells
            .get(1)
            .and_then(|c| c.strip_prefix('`'))
            .and_then(|c| c.strip_suffix('`'))
        else {
            continue;
        };
        if !seen.insert(name.to_string()) {
            continue;
        }
        let id = upper(name);
        if name.starts_with("spring.") {
            let response: f32 = cells.get(2).and_then(|c| c.parse().ok()).ok_or("spring response")?;
            let damping: f32 = cells.get(3).and_then(|c| c.parse().ok()).ok_or("spring ζ")?;
            let _ = writeln!(
                code,
                "    /// `{name}`.\n    pub const {id}: SpringToken = SpringToken {{ response: {}, damping_ratio: {} }};",
                f(response),
                f(damping)
            );
        } else if name.starts_with("fade.") || name.starts_with("delay.") {
            let ms: f32 = cells
                .get(2)
                .and_then(|c| c.split_whitespace().next())
                .and_then(|c| c.parse().ok())
                .ok_or("duration")?;
            let _ = writeln!(
                code,
                "    /// `{name}` duration in seconds.\n    pub const {id}: f32 = {};",
                f(ms / 1000.0)
            );
            if name.starts_with("fade.") {
                let curve = cells.get(3).copied().unwrap_or_default();
                let named = if let (Some(a), Some(b)) = (curve.find('('), curve.find(')')) {
                    let nums: Vec<f32> = curve
                        .get(a + 1..b)
                        .unwrap_or_default()
                        .split(',')
                        .filter_map(|x| x.trim().parse().ok())
                        .collect();
                    if let [x1, y1, x2, y2] = nums[..] {
                        let label = curve.get(..a).unwrap_or_default().trim().to_string();
                        curves.push((label, [x1, y1, x2, y2]));
                    }
                    curve.get(..a).unwrap_or_default().trim().to_string()
                } else {
                    curve.trim().to_string()
                };
                let _ = writeln!(
                    code,
                    "    /// `{name}` curve.\n    pub const {id}_CURVE: Cubic = {};",
                    upper(&named)
                );
            }
        }
    }
    for (label, [a, b, c, d]) in &curves {
        let _ = writeln!(
            code,
            "    /// `{label}` ({a}, {b}, {c}, {d}).\n    pub const {}: Cubic = Cubic::new({}, {}, {}, {});",
            upper(label),
            f(*a),
            f(*b),
            f(*c),
            f(*d)
        );
    }
    code.push_str("}\n");
    Ok(())
}

fn symbols(points: &Value) -> Result<String> {
    let map = points.as_object().ok_or("codepoints not an object")?;
    let mut entries: Vec<(String, u32)> = Vec::new();
    for (k, v) in map {
        let cp = v
            .as_str()
            .and_then(|s| u32::from_str_radix(s, 16).ok())
            .ok_or_else(|| format!("bad codepoint for {k}"))?;
        entries.push((k.clone(), cp));
    }
    entries.sort();
    let mut code = String::from(
        "// GENERATED from data/silica-symbols-codepoints.json. Do not edit.\n\n\
         /// Every Silica Symbols glyph by name, sorted, with its codepoint.\n\
         pub static SYMBOLS: &[(&str, u32)] = &[\n",
    );
    for (k, cp) in entries {
        let _ = writeln!(code, "    ({k:?}, 0x{cp:04X}),");
    }
    code.push_str("];\n");
    Ok(code)
}
